export function buildDeck() {
  const deck = [];
  let id = 0;
  ACTORS.forEach((name) => deck.push({ id: `c${id++}`, type: 'actor', name }));
  MOVIES.forEach((name) => deck.push({ id: `c${id++}`, type: 'movie', name }));
  SERIES.forEach((name) => deck.push({ id: `c${id++}`, type: 'series', name }));
  COMMANDS.forEach((cmd) => {
    for (let i = 0; i < 3; i++) {
      deck.push({ id: `c${id++}`, type: 'command', name: cmd.name, key: cmd.key, desc: cmd.desc });
    }
  });
  return deck; // 185 كارت (70 ممثل + 50 فيلم + 50 مسلسل + 15 كوماند)
}

